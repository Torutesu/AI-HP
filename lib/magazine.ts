// Magazine content source.
// A single, typed data module drives the list page, the category filter, the
// per-article detail pages (/magazine/[slug]) and the sitemap. To publish a new
// article, add an entry here (or migrate to MDX/CMS later — see README).

export type Article = {
  slug: string;
  category: string;
  title: string;
  date: string; // published, "YYYY.MM.DD"
  updatedAt?: string; // last updated, "YYYY.MM.DD"; falls back to `date`
  // Publication state (human-review gate). Omitted or "published" = live.
  // "draft" = written but NOT yet approved by a human reviewer: excluded from
  // the list, sitemap, RSS and llms.txt, and marked noindex with a review
  // banner on its detail page (previewable by URL only). Flip to "published"
  // once a human has reviewed it. New skill-authored articles start as "draft".
  status?: "draft" | "published";
  excerpt: string;
  // Conclusion-first "short answer" (2-4 sentences) shown in a highlighted box
  // at the top of the article. Directly answers the article's core question so
  // both readers and AI answer engines get the payoff up front (LLMO). Distinct
  // from `excerpt`, which is the teaser used for meta/OG and list cards.
  summary?: string;
  featured?: boolean;
  image?: string; // absolute or root-relative OG/Article image; falls back site-wide
  // Body blocks, rendered in order by /magazine/[slug]:
  //   "## <text>"          — section heading (h2)
  //   "- a\n- b\n- c"      — bullet list (one string, newline-separated items)
  //   "※<text>"            — small-print note (disclaimers, as-of dates)
  //   anything else        — paragraph
  body: string[];
  // Optional FAQ, rendered at the foot of the article and emitted as FAQPage
  // JSON-LD for rich results / LLM answer-engine citation. Keep answers
  // self-contained (one short paragraph) so they read well when quoted alone.
  faq?: { q: string; a: string }[];
  // Curated related-article slugs for topic-cluster internal linking. Shown
  // (in order) in the "関連する記事" block; may cross categories. Falls back to
  // same-category articles when fewer than 3 are given. Body text may also carry
  // inline links via markdown "[label](/magazine/slug)".
  related?: string[];
};

/** Published/updated date as an ISO (YYYY-MM-DD) string for schema + sitemap. */
export function isoDate(a: Article): string {
  return (a.updatedAt ?? a.date).replace(/\./g, "-");
}
export function isoPublished(a: Article): string {
  return a.date.replace(/\./g, "-");
}

